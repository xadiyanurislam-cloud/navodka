# Сколько слов берём за один прогон.
#
# Каждое лишнее слово — это полный обход всех источников по всем
# городам заново. Пять слов по трём городам и пяти источникам — это
# семьдесят пять запросов к чужим серверам, и ждать их приходится
# человеку. Четыре близких слова к основному ловят почти весь смысл
# списка, дальше растёт только время.
MAX_WORDS = 5


def words_for(query, limit=MAX_WORDS):
    """Слово и близкие к нему — для обхода за один прогон.

    Само слово всегда первое: если предел исчерпан на середине, обход
    должен был успеть сделать главное.
    """
    q = (query or "").strip()
    if not q:
        return []
    out = [q]
    for w in ALSO.get(q, []) or ALSO.get(q.lower(), []) or []:
        if w.lower() not in [o.lower() for o in out]:
            out.append(w)
    return out[:max(1, int(limit or 1))]
