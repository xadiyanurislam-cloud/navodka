def tagged(query):
    """Ищется ли это слово по тегам карты, а не только по названию.

    Считаем по тому же словарю, которым пользуется сам поиск: пометка,
    проставленная руками, рано или поздно разойдётся с делом.
    """
    low = (query or "").lower()
    return any(word in low for word in osm.TAGS)


def catalog():
    """Список для интерфейса: темы со словами и признаком тега."""
    return [{"title": title,
             "items": [{"q": q, "tagged": tagged(q)} for q in items]}
            for title, items in GROUPS]


def all_words():
    """Все слова одним списком — для подсказки к полю ввода."""
    out = []
    for _title, items in GROUPS:
        for q in items:
            if q not in out:
                out.append(q)
    return out

