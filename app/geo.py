def region_code(name):
    """Номер субъекта РФ по городу или региону. Пусто — вся страна."""
    return REGION_CODE.get((name or "").strip(), "")


def _spn(lon, lat, radius_km):
    """Охват в градусах из радиуса в километрах.

    По широте градус везде одинаков, по долготе — сужается к полюсам,
    поэтому на долготу делим на косинус широты. Без этого Мурманск
    получил бы прямоугольник вдвое уже нужного.
    """
    dlat = 2.0 * radius_km / 111.0
    dlon = dlat / max(0.2, math.cos(math.radians(lat)))
    return "%.4f,%.4f" % (dlon, dlat)


def cities():
    """[{name, part, gis, hh, ll, spn}] — город и его номер в каждом справочнике.

    Ноль или пустая строка в поле означает, что этот источник город не
    знает: у 2ГИС нет «России целиком», а из полутора сотен городов в его
    справочнике и в справочнике hh есть заметно меньше. Поиск такой
    источник для такого города пропускает — и говорит об этом.
    """
    hh_by_name = {name: code for code, name in hh.AREAS}
    gis_by_name = dict(gis2.CITIES)
    out = [{"name": WHOLE, "part": "", "region": "", "gis": 0, "hh": "113",
            "ll": "", "spn": ""}]
    for name, part, lon, lat, radius in CITIES:
        name = name.strip()
        out.append({"name": name, "part": part,
                    "region": REGION_CODE.get(name, ""),
                    "gis": gis_by_name.get(name, 0),
                    "hh": hh_by_name.get(name, ""),
                    "ll": "%.4f,%.4f" % (lon, lat),
                    "spn": _spn(lon, lat, radius)})
    return out


def groups():
    """Города по федеральным округам — для выпадающего списка.

    Полторы сотни строк одним полотном не читаются: человек ищет «Пермь»
    и пролистывает мимо. Округ даёт ориентир, а поиск по буквам внутри
    списка — быстрый путь для тех, кто знает, что хочет.
    """
    out, seen = [], {}
    for c in cities():
        if c["name"] == WHOLE:
            continue
        if c["part"] not in seen:
            seen[c["part"]] = []
            out.append({"title": c["part"], "items": seen[c["part"]]})
        seen[c["part"]].append(c)
    return out


def pick(names):
    """Выбранные города по названиям, в порядке справочника."""
    want = {str(n).strip() for n in (names or []) if str(n).strip()}
    rows = [c for c in cities() if c["name"] in want]
    return rows or [c for c in cities() if c["name"] == WHOLE]
